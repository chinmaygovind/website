COUNTRY_NAMES = dict(COUNTRIES)
US_STATE_NAMES = dict(US_STATES)


def flag_of(country, state=None, prefer_state=False):
    """The flag a profile flies, as ``(url_path, alt_text)`` - or ``None``.

    ``url_path`` is relative to the site root, so a game on another subdomain
    prefixes it with the main site's URL and everything here stays one copy.
    A state flag is only ever flown by someone in the US who asked for it; any
    other combination falls back to the country, and no country means no flag
    at all rather than a placeholder.
    """
    country = (country or "").lower() or None
    state = (state or "").upper() or None
    if country == "us" and prefer_state and state in US_STATE_NAMES:
        return ("/assets/flags/us/%s.png" % state.lower(), US_STATE_NAMES[state])
    if country in COUNTRY_NAMES:
        return ("/assets/flags/country/%s.svg" % country, COUNTRY_NAMES[country])
    return None


def place_name(country, state=None):
    """Where someone is from, in words: "California, United States"."""
    country = (country or "").lower()
    state = (state or "").upper()
    cname = COUNTRY_NAMES.get(country)
    if not cname:
        return None
    if country == "us" and state in US_STATE_NAMES:
        return "%s, %s" % (US_STATE_NAMES[state], cname)
    return cname
