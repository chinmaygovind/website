    function durian(x, gy, z, ax, az, ra, rb, h) {
      // **Not a gold globe.** The first two passes were bright gold triangles
      // on a round dome and read as a beach ball and then as a golden egg. The
      // real Esplanade is a low, slightly pointed shell of grey aluminium
      // sunshades - 7,000 of them - and at night the glow is the theatre inside,
      // seen *through* the gaps: a silver-grey roof that the lamps catch on top,
      // darkening down its flanks, with warm light leaking out low down and
      // through the glazing at its foot.
      const lx = -az, lz = ax;
      const NU = 64, NV = 14;
      const P = (u, v) => {
        const th = (u / NU) * Math.PI * 2, t = Math.min(1, v / NV);
        // a flatter, slightly pointed profile rather than a hemisphere
        const ph = t * Math.PI / 2, rr = Math.cos(ph), hh = Math.pow(Math.sin(ph), 0.8);
        const cx = Math.cos(th) * rr * ra, cz = Math.sin(th) * rr * rb;
        return [x + ax * cx + lx * cz, gy + hh * h, z + az * cx + lz * cz];
      };
      const mid = (A, B, t) => [A[0] + (B[0] - A[0]) * t, A[1] + (B[1] - A[1]) * t, A[2] + (B[2] - A[2]) * t];
      for (let v = 0; v < NV; v++) {
        const nu = Math.max(8, Math.round(NU * Math.cos((v + 0.5) / NV * Math.PI / 2)));
        for (let k = 0; k < nu; k++) {
          const u0 = (k / nu) * NU, u1 = ((k + 1) / nu) * NU;
          const A = P(u0, v), B = P(u1, v), Cc = P(u1, v + 1), D = P(u0, v + 1);
          const out = [(A[0] + Cc[0]) / 2 - x, (A[1] + Cc[1]) / 2 - gy + h * 0.3, (A[2] + Cc[2]) / 2 - z];
          // the shell: lit grey metal, so the floodlight shades it top to flank
          wound(solid, A, B, Cc, D, out, shade(0x8a8c90, (rMisc() - 0.5) * 0.08));
          // a sunshade spike standing proud of every cell: a small pyramid
          const m = Math.hypot(out[0], out[1], out[2]) || 1, nrm = [out[0] / m, out[1] / m, out[2] / m];
          const c0 = mid(mid(A, B, 0.5), mid(D, Cc, 0.5), 0.5);
          const tip = [c0[0] + nrm[0] * 0.9, c0[1] + nrm[1] * 0.9, c0[2] + nrm[2] * 0.9];
          const q0 = mid(A, c0, 0.3), q1 = mid(B, c0, 0.3), q2 = mid(Cc, c0, 0.3), q3 = mid(D, c0, 0.3);
          const metal = 0xa2a4a8;
          solid.tri(q0, q1, tip, metal); solid.tri(q1, q2, tip, shade(metal, -0.12));
          solid.tri(q2, q3, tip, shade(metal, -0.2)); solid.tri(q3, q0, tip, shade(metal, -0.08));
          // the glow through the gaps, strongest low down
          if (v < NV * 0.55 && rMisc() < 0.55 - v / NV * 0.6) {
            const g = mid(mid(A, Cc, 0.5), mid(B, D, 0.5), 0.5);
            const e1 = mid(A, B, 0.5), e2 = mid(D, Cc, 0.5);
            const ga = [g[0] + nrm[0] * 0.05, g[1] + nrm[1] * 0.05, g[2] + nrm[2] * 0.05];
            const w = mid(e1, ga, 0.55), w2 = mid(e2, ga, 0.55);
            bright.tri(w, mid(A, ga, 0.6), w2, shade(0x3a2408, (rMisc() - 0.5) * 0.4));
            bright.tri(w2, mid(A, ga, 0.6), w, shade(0x3a2408, (rMisc() - 0.5) * 0.4));
          }
        }
      }
      // the glazed foyer round its foot, lit warm
      for (let k = 0; k < NU; k++) {
        const A = P(k, 0), B = P(k + 1, 0);
        face2(bright, A, B, [B[0], B[1] + 2.0, B[2]], [A[0], A[1] + 2.0, A[2]], 0x4a3214);
      }
    }

